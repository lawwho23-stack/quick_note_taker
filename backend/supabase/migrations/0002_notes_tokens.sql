-- 0002_notes_tokens.sql
-- Notes, and the revocable tokens the browser extension uses to create them.
--
-- Isolation: every note query runs with `app.user_id` set for the transaction
-- (set_config(..., true)), and row-level security limits qn_runtime to that
-- account's rows. A bug that forgets a `where user_id = ...` still cannot read
-- or write another account's notes.

-- Substring search that also works for scripts without spaces (Burmese, Thai).
create extension if not exists pg_trgm;

-- app.notes -----------------------------------------------------------------
create table if not exists app.notes (
  id           uuid primary key,  -- generated by the client, so retries are idempotent
  user_id      uuid not null references app.users (id) on delete cascade,
  body         text not null check (char_length(body) <= 20000),
  version      integer not null default 1 check (version >= 1),
  source       text not null default 'web',
  meta         jsonb not null default '{}'::jsonb,
  payload_hash text not null,     -- sha-256 of the create payload, for idempotent retries
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  deleted_at   timestamptz
);

comment on table app.notes is 'Quick Note notes. Client-supplied ids; soft-deleted via deleted_at.';
comment on column app.notes.payload_hash is 'Hash of the create request; a retry with a different payload is a 409.';

create index if not exists notes_user_created_idx
  on app.notes (user_id, created_at desc, id desc)
  where deleted_at is null;

create index if not exists notes_body_trgm_idx
  on app.notes using gin (body gin_trgm_ops);

drop trigger if exists notes_touch_updated_at on app.notes;
create trigger notes_touch_updated_at
  before update on app.notes
  for each row
  execute function app.touch_updated_at();

alter table app.notes owner to qn_owner;
grant select, insert, update on app.notes to qn_runtime;

alter table app.notes enable row level security;
alter table app.notes force row level security;

drop policy if exists notes_owner on app.notes;
create policy notes_owner on app.notes
  for all
  to qn_runtime
  using (user_id = nullif(current_setting('app.user_id', true), '')::uuid)
  with check (user_id = nullif(current_setting('app.user_id', true), '')::uuid);

-- app.extension_tokens ------------------------------------------------------
-- Looked up by hash before any account is known, so this table has no RLS.
-- Only the API reaches it; the schema is closed to the browser-facing roles.
create table if not exists app.extension_tokens (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid not null references app.users (id) on delete cascade,
  token_hash   text not null unique,  -- sha-256 of the secret; the secret is never stored
  label        text,
  scopes       text[] not null default '{notes:create}',
  created_at   timestamptz not null default now(),
  last_used_at timestamptz,
  revoked_at   timestamptz
);

comment on table app.extension_tokens is 'Revocable extension tokens. Only the sha-256 hash is stored.';

create index if not exists extension_tokens_user_idx on app.extension_tokens (user_id);

alter table app.extension_tokens owner to qn_owner;
grant select, insert, update on app.extension_tokens to qn_runtime;
